  <!-- ============ READING THE DIAGRAMS ============ -->
  <section class="chapter" id="reading-diagrams">
    <div class="chapter-head"><span class="chapter-num">2.5</span><h2>How to Read PCA vs t-SNE Output Diagrams</h2></div>
    
    <p>A common exam requirement is being able to interpret the scatterplots generated by PCA and t-SNE. Because their mathematical goals are completely different, their visualizations look vastly different.</p>

    <div class="concept-cards" style="grid-template-columns: 1fr;">
      
      <div class="concept-card">
        <h4>1. Reading a PCA Diagram</h4>
        <p><strong>What it looks like:</strong> A giant, continuous "smear" or cloud of dots (often shaped like an oval). You generally won't see distinct, clearly separated islands.</p>
        <p><strong>How to interpret it:</strong></p>
        <ul>
          <li><strong>The Axes:</strong> The X-axis is PC1 (the direction capturing the absolute most variance). The Y-axis is PC2.</li>
          <li><strong>Global Truth:</strong> PCA preserves global structure. If two dots are far apart on the plot, they are truly, mathematically very different from each other.</li>
          <li><strong>The Takeaway:</strong> It shows the "big picture", but because it is a rigid linear projection, it is terrible at pulling apart small, distinct sub-groups.</li>
        </ul>
      </div>

      <div class="concept-card">
        <h4>2. Reading a t-SNE Diagram</h4>
        <p><strong>What it looks like:</strong> An archipelago of separated "islands" or "blobs" of dots, with distinct white space separating them.</p>
        <p><strong>How to interpret it (Watch out for these Exam Traps!):</strong></p>
        <ul>
          <li><strong>The Axes mean nothing:</strong> The numbers on the X and Y axes are entirely arbitrary.</li>
          <li><strong>Local Neighbors:</strong> If dots are clustered together inside the same island, they are highly similar. t-SNE excels at finding local groupings (like specific cell types).</li>
          <li><strong class="important-term">TRAP 1: Distance is meaningless!</strong> If Island A is plotted right next to Island B, but Island C is far away, it <strong>does not mean</strong> Island A and B are related! t-SNE artificially expands empty space between clusters. You cannot trust the distance between different islands.</li>
          <li><strong class="important-term">TRAP 2: Size is meaningless!</strong> If one cluster is a tight dot and another is a huge spread-out blob, it does not mean the blob has more variance. t-SNE dynamically stretches areas to make them fit on the screen.</li>
        </ul>
      </div>

    </div>
  </section>

  <!-- ============ WHY BOTH ============ -->
END_HTML

